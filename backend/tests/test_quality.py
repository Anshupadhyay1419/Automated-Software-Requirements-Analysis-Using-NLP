"""Quality rule tests, plus LLM filtering with made-up LLM answers."""
from app.nlp import quality
from app.nlp.quality import LLMIssue, LLMReview, check_rules, llm_review, rule_contradiction


def kinds(text, category=None):
    return {issue["kind"] for issue in check_rules(text, category)}


def test_brief_example_very_fast():
    issues = check_rules("The website should be very fast.")
    assert issues[0]["message"] == "Ambiguous performance requirement."
    assert issues[0]["question"] == "What response-time target should the website meet?"


def test_user_friendly_is_vague():
    assert "vague_expression" in kinds("The app must be user-friendly.")


def test_clear_requirement_has_no_issues():
    assert check_rules("Users can reset their password.") == []


def test_performance_without_number_needs_measure():
    assert "missing_measure" in kinds("Pages must load well.", "performance")


def test_performance_with_number_is_fine():
    assert "missing_measure" not in kinds("Pages must load in 2 seconds.", "performance")


def test_pronoun_actor_is_unclear():
    assert "unclear_actor" in kinds("It should send emails.")


def test_passive_without_actor_is_unclear():
    assert "unclear_actor" in kinds("Reports are generated every week.")


def test_passive_with_actor_is_fine():
    assert "unclear_actor" not in kinds("Reports are generated by the billing service.")


def test_pronoun_in_subordinate_clause_is_ignored():
    assert "unclear_actor" not in kinds("Customers must not cancel an order after it has been shipped.")


def test_etc_is_unspecified():
    assert "unspecified_behavior" in kinds("The system should send emails, alerts, etc.")


def test_generic_verb_is_unspecified():
    assert "unspecified_behavior" in kinds("The system should handle errors.")


def test_generic_verb_with_number_is_fine():
    assert "unspecified_behavior" not in kinds("The system must process 100 payments per second.")


def test_negation_contradiction():
    assert rule_contradiction("Users can delete posts.", "Users must not delete posts.")


def test_number_contradiction():
    assert rule_contradiction("Results must appear within 2 seconds.", "Search results must appear within 5 seconds.")


def test_different_subjects_are_not_a_contradiction():
    assert rule_contradiction("Customers can place orders.", "Guests must not place orders.") is None


def test_no_difference_is_not_a_contradiction():
    assert rule_contradiction("Users can log in.", "Users can sign in.") is None


def make_review(**fields):
    return LLMReview(issues=[LLMIssue(message="m", question="q", **fields)])


def test_llm_evidence_must_come_from_the_requirement(monkeypatch):
    monkeypatch.setattr(quality, "ask_llm", lambda *_: make_review(kind="vague_expression", evidence="blazing speed"))
    assert llm_review("Users can log in.") == []


def test_llm_evidence_from_requirement_is_kept(monkeypatch):
    monkeypatch.setattr(quality, "ask_llm", lambda *_: make_review(kind="vague_expression", evidence="look good"))
    assert len(llm_review("The app should look good.")) == 1


def test_llm_cannot_claim_missing_measure_when_number_exists(monkeypatch):
    monkeypatch.setattr(quality, "ask_llm", lambda *_: make_review(kind="missing_measure", evidence="99.9%"))
    assert llm_review("The site must be available 99.9% of the time.") == []
